/// [pattern] : motif de la route courante (ex. `/family/challenges/:id`),
/// [path] : adresse concrète.
String titleForRoute({String? pattern, required String path}) {
  if (pattern != null) {
    final exact = routeTitles[pattern];
    if (exact != null) return exact;
  }
  final exactPath = routeTitles[path];
  if (exactPath != null) return exactPath;
  final segments = path.split('/').where((s) => s.isNotEmpty);
  if (segments.isNotEmpty) {
    final section = sectionTitles[segments.first];
    if (section != null) return section;
  }
  return 'PharmaConnect';
}
